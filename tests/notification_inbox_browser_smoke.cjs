// Run only with a disposable API database seeded with inbox-first and inbox-second users.
// The first user's inbox must contain one "Browser HR notice" addressed to them.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base=process.env.SASS_INBOX_TEST_BASE||'http://127.0.0.1:5173';
const password='SyntheticBrowser-2026!';
if(process.env.SASS_HRM_TESTING!=='1')throw Error('Disposable stack required');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const errors=[];
 async function login(username){
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  page.setDefaultTimeout(12000);
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/sign-in');
  await page.locator('#sass-login-email').fill(username+'@test.invalid');
  await page.locator('#sass-login-password').fill(password);
  await page.getByRole('button',{name:'Sign in to SASS HRM'}).click();
  await page.locator('.gd').waitFor();
  await page.goto(base+'/workspace/notifications');
  await page.locator('.wc-page .wc-header h1').first().waitFor();
  return page;
 }
 try{
  const page=await login('inbox-first');
  const notices=page.locator('.wc-panel').filter({has:page.getByRole('heading',{name:'HR notifications',exact:true})});
  const article=notices.getByRole('article').filter({hasText:'Browser HR notice'});
  await article.getByRole('button',{name:'Mark read',exact:true}).click();
  await article.getByRole('button',{name:'Mark unread',exact:true}).click();
  await article.getByRole('button',{name:'Archive',exact:true}).click();
  await notices.getByRole('button',{name:'Archived',exact:true}).click();
  await article.getByRole('button',{name:'Restore',exact:true}).click();
  await notices.getByRole('button',{name:'All',exact:true}).click();
  await notices.getByLabel('Find a notification').fill('no matching text for this phrase');
  await notices.getByRole('button',{name:'Search',exact:true}).click();
  await notices.getByText('No notifications match your search.').waitFor();
  await notices.getByRole('button',{name:'Clear search',exact:true}).click();
  await article.waitFor();
  const bulkGroup=notices.getByRole('group',{name:'Confirm bulk notification action',exact:true});
  await notices.getByRole('button',{name:'Select notifications',exact:true}).click();
  await article.getByRole('checkbox',{name:'Select notification: Browser HR notice',exact:true}).check();
  await notices.getByRole('button',{name:'Archive selected',exact:true}).click();
  await bulkGroup.getByRole('button',{name:'Cancel bulk action',exact:true}).click();
  await article.waitFor();
  await notices.getByRole('button',{name:'Clear selection',exact:true}).click();
  await notices.getByRole('button',{name:'Select this page',exact:true}).click();
  await notices.getByRole('button',{name:'Mark selected read',exact:true}).click();
  await bulkGroup.getByRole('button',{name:'Confirm mark read',exact:true}).click();
  await page.getByText('selected notifications marked read.',{exact:false}).waitFor();
  await notices.getByRole('button',{name:'Select this page',exact:true}).click();
  await notices.getByRole('button',{name:'Mark selected unread',exact:true}).click();
  await bulkGroup.getByRole('button',{name:'Confirm mark unread',exact:true}).click();
  await page.getByText('selected notifications marked unread.',{exact:false}).waitFor();
  await notices.getByRole('button',{name:'Select this page',exact:true}).click();
  await notices.getByRole('button',{name:'Archive selected',exact:true}).click();
  await bulkGroup.getByRole('button',{name:'Confirm archive',exact:true}).click();
  await article.waitFor({state:'hidden'});
  await notices.getByRole('button',{name:'Archived',exact:true}).click();
  await article.waitFor();
  assert.equal(await notices.getByRole('button',{name:'Archive selected',exact:true}).count(),0);
  await notices.getByRole('button',{name:'Select this page',exact:true}).click();
  await notices.getByRole('button',{name:'Restore selected',exact:true}).click();
  await bulkGroup.getByRole('button',{name:'Confirm restore',exact:true}).click();
  await article.waitFor({state:'hidden'});
  await notices.getByRole('button',{name:'All',exact:true}).click();
  await article.waitFor();
  await notices.getByRole('button',{name:'Exit selection',exact:true}).click();
  await notices.getByText('Inbox settings',{exact:true}).click();
  await notices.getByLabel('Default to unread-only inbox').check();
  await page.getByText('Inbox preferences saved.',{exact:true}).waitFor();
  await notices.getByLabel('Default notification sort').selectOption('oldest');
  await notices.getByLabel('Notifications per page').selectOption('10');
  await notices.getByLabel('Default reminder view').selectOption('due');
  const sizedFetch=page.waitForResponse(r=>r.url().includes('/api/workspace/inbox?')&&r.url().includes('limit=10')&&r.url().includes('order=oldest')&&r.ok());
  await notices.getByRole('button',{name:'Save display defaults',exact:true}).click();
  await page.getByText('Display defaults saved.',{exact:true}).waitFor();
  await sizedFetch;

  const reminders=page.getByRole('region',{name:'Personal reminders'});
  const card=reminders.getByRole('article').filter({hasText:'Browser reminder'});
  await reminders.getByRole('button',{name:'Add reminder',exact:true}).click();
  await reminders.getByLabel('Title',{exact:true}).fill('Browser reminder');
  await reminders.getByLabel('Notes (optional)',{exact:true}).fill('Personal, not an HR notice.');
  await reminders.getByLabel('Due date (optional)',{exact:true}).fill('2001-11-30');
  await reminders.getByRole('button',{name:'Save reminder',exact:true}).click();
  await card.getByText('Open · Due 2001-11-30').waitFor();
  await card.getByText('Overdue',{exact:true}).waitFor();
  await page.reload();
  await notices.getByRole('button',{name:'Unread',exact:true,pressed:true}).waitFor();
  await reminders.getByRole('button',{name:'Due now',exact:true,pressed:true}).waitFor();
  assert.equal(await notices.getByLabel('Sort by',{exact:true}).inputValue(),'oldest');
  await reminders.getByRole('button',{name:'Upcoming',exact:true}).click();
  await reminders.getByText('No reminders in this view.').waitFor();
  await reminders.getByRole('button',{name:'Due now',exact:true}).click();
  await card.getByRole('button',{name:'Edit',exact:true}).click();
  await reminders.getByLabel('Title',{exact:true}).fill('Browser reminder revised');
  await reminders.getByRole('button',{name:'Save reminder',exact:true}).click();
  await card.getByText('Browser reminder revised',{exact:true}).waitFor();
  const other=await login('inbox-second');
  await other.getByRole('region',{name:'Personal reminders'}).getByText('No reminders in this view.').waitFor();
  assert.equal(await other.getByText('Browser reminder revised',{exact:true}).count(),0);
  await card.getByRole('button',{name:'Complete',exact:true}).click();
  await reminders.getByRole('button',{name:'Completed',exact:true}).click();
  await card.getByRole('button',{name:'Reopen',exact:true}).click();
  await reminders.getByRole('button',{name:'Open',exact:true}).click();
  await card.getByRole('button',{name:'Delete',exact:true}).click();
  await card.getByRole('button',{name:'Keep reminder',exact:true}).click();
  await card.getByRole('button',{name:'Delete',exact:true}).click();
  await card.getByRole('button',{name:'Confirm deletion',exact:true}).click();
  await reminders.getByText('No reminders in this view.').waitFor();
  await page.reload();
  await reminders.getByText('No reminders in this view.').waitFor();
  await notices.getByText('Inbox settings',{exact:true}).click();
  await notices.getByRole('button',{name:'Reset preferences',exact:true}).click();
  await page.getByText('Inbox preferences saved.',{exact:true}).waitFor();
  await notices.getByRole('button',{name:'Reset display defaults',exact:true}).click();
  await page.getByText('Display defaults reset.',{exact:true}).waitFor();
  await page.reload();
  await reminders.getByRole('button',{name:'Open',exact:true,pressed:true}).waitFor();
  assert.equal(await notices.getByLabel('Sort by',{exact:true}).inputValue(),'newest');
  assert.deepEqual(errors,[]);
  console.log('PASS: browser single/bulk notification actions, search, saved display defaults and private reminder add/edit/completion/reopen/confirmed delete');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
